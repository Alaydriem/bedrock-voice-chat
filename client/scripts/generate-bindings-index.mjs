import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/**
 * Regenerates the bindings barrel from whatever ts-rs emitted.
 *
 * ts-rs writes one file per type and no index, and a hand-maintained barrel
 * drifts: it listed 32 of 88 types before this existed. Every emitted file
 * exports a single type whose name matches the filename, which is what makes
 * this derivable rather than curated.
 *
 * Run after the Rust build, never before: the files this reads are written by
 * cargo, which runs after Tauri's beforeBuildCommand.
 */
const dir = fileURLToPath(new URL("../src/js/bindings/", import.meta.url));

const names = readdirSync(dir)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts")
  .map((f) => f.replace(/\.ts$/, ""))
  .sort();

const body = names.map((n) => `export type { ${n} } from './${n}';`).join("\n");

writeFileSync(
  `${dir}index.ts`,
  `// Generated by scripts/generate-bindings-index.mjs. Do not edit.\n${body}\n`,
);
console.log(`bindings: ${names.length} types`);
